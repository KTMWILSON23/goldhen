#!/usr/bin/env python3
"""Embed the audited rainbow ShellUI PRX in the BinLoader payload source."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


def format_bytes(data: bytes) -> str:
    rows = []
    for offset in range(0, len(data), 12):
        chunk = data[offset : offset + 12]
        rows.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    return "\n".join(rows)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--manifest", required=True, type=Path)
    args = parser.parse_args()

    data = args.input.read_bytes()
    if len(data) < 4096:
        raise SystemExit("refusing to embed an implausibly small PRX")

    digest = hashlib.sha256(data).hexdigest()
    source = (
        "/* Generated by tools/embed_prx.py; do not edit. */\n"
        "#include <stddef.h>\n\n"
        f"/* SHA-256: {digest} */\n"
        "const unsigned char embedded_shellui_prx[] = {\n"
        + format_bytes(data)
        + "\n};\n"
        "const size_t embedded_shellui_prx_len = sizeof(embedded_shellui_prx);\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(source, encoding="ascii", newline="\n")

    record = {
        "component": args.input.name,
        "sha256": digest,
        "size": len(data),
    }
    args.manifest.write_text(
        json.dumps(record, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"embedded {len(data)} bytes, sha256={digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
